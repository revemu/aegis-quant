function formatTimestamp(d = new Date()): string {
  try {
    const tz = config.timezone || process.env.TZ || "Asia/Bangkok";
    const formatter = new Intl.DateTimeFormat("sv-SE", {
      timeZone: tz,
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hour12: false,
    });
    const ms = String(d.getMilliseconds()).padStart(3, "0");
    return `${formatter.format(d)}.${ms}`;
  } catch {
    const pad = (n: number) => String(n).padStart(2, "0");
    const padMs = (n: number) => String(n).padStart(3, "0");
    return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}.${padMs(d.getMilliseconds())}`;
  }
}

function getStrategyLogTag(): string {
  if (config.strategyType === "ma_ribbon") return "ma-ribbon";
  if (config.strategyType === "swing_trade") return "swing-trade";
  return "dynamic-grid";
}

function log(msg: string, extra?: unknown): void {
  let cleanMsg = msg;
  if (
    typeof msg === "string" &&
    (msg.includes("Generated by cloudfront") ||
      msg.includes("<!DOCTYPE") ||
      msg.includes("<BODY>") ||
      msg.includes("</HTML>") ||
      msg.includes("<HTML>"))
  ) {
    cleanMsg = sanitizeHttpErrorBody("LOG", msg);
  }
  const line = `[${getStrategyLogTag()} ${formatTimestamp()}] ${cleanMsg}`;
  if (extra !== undefined) console.log(line, extra);
  else console.log(line);
}

type ManagedCandleFeed = AtrSource & {
  start(): void | Promise<void>;
  stop(): void;
  onCandle(fn: (candle: Candle, isClosed: boolean) => void): void;
};

type ManagedBookFeed = {
  start(): void;
  stop(): void;
  onBook(fn: (b: any) => void): void;
};

function buildExchangeAdapter(exchangeName: string, src: Record<string, any>): IExchangeClient {
  const norm = (exchangeName || "binance").toLowerCase();
  if (norm === "alpaca") {
    return createExchangeClient({
      exchange: "alpaca",
      apiKey: src.alpacaApiKey,
      apiSecret: src.alpacaApiSecret,
      baseUrl: src.alpacaBaseUrl,
      dataUrl: src.alpacaDataUrl,
      log: (msg) => log(`[alpaca] ${msg}`),
    });
  }
  return createExchangeClient({
    exchange: norm,
    apiKey: src.binanceApiKey,
    apiSecret: src.binanceApiSecret,
    baseUrl: src.binanceBaseUrl,
    privateKey: src.dreamdexPrivateKey,
    rpcUrl: src.dreamdexRpcUrl,
    log: (msg) => log(`[${norm}] ${msg}`),
  });
}

async function main(): Promise<void> {
  const pairRotator = new AutonomousPairRotator((msg) => log(msg));
  const startupExchange = (config.exchange || "binance").toLowerCase();
  let exchange = buildExchangeAdapter(startupExchange, config);

  await exchange.syncTime();

  let rawStartupSymbol = (config.symbol || (startupExchange === "alpaca" ? "AAPL" : "BTCUSDT")).toUpperCase().replace(/[\/\-_:]/g, "");
  if (startupExchange === "alpaca") {
    const cleanStock = normalizeStockSymbol(rawStartupSymbol);
    rawStartupSymbol = ["BTCUSDT", "BTCFDUSD", "ETHUSDT", "ETHFDUSD", "SOMI", "SOMIUSDSO"].includes(rawStartupSymbol)
      ? "AAPL"
      : (cleanStock || "AAPL");
  }
  let activeSymbol = rawStartupSymbol;
  let symbolInfo = await exchange.getExchangeInfo(activeSymbol);

  log(
    `📊 Spot Market (${exchange.exchangeName.toUpperCase()}): ${symbolInfo.symbol} (${symbolInfo.baseAsset}/${symbolInfo.quoteAsset}) ` +
      `| minQty: ${symbolInfo.minQty} | stepSize: ${symbolInfo.stepSize} | tickSize: ${symbolInfo.tickSize} | minNotional: $${symbolInfo.minNotional}`,
  );

  // ── Dow Theory & Market Structure Engines ────────────────────────────────
  // 1. Macro Engine (15m/1h): establishes the solid 0% Floor, 50% Center, 100% Ceiling
  const macroDowEngine = new DowStructureEngine(
    config.dowSwingLookback,
    config.useTrueWick,
    config.wickThresholdPct,
    config.maxCandleCount ?? 600,
  );
  // 2. Local Trend Engine (15m): detects localized downtrends to pause buys during drops
  const localTrendEngine = new DowStructureEngine(
    config.dowSwingLookback,
    config.useTrueWick,
    config.wickThresholdPct,
    config.maxCandleCount ?? 600,
  );
  // 3. HTF Anchor Engine (4h): establishes institutional macro support floor and ceiling
  const htfDowEngine = new DowStructureEngine(
    config.dowSwingLookback,
    config.useTrueWick,
    config.wickThresholdPct,
    config.maxCandleCount ?? 600,
  );

  // Preload macro candles, trading candles, and HTF candles on boot
  let macroFeed: ManagedCandleFeed | undefined;
  let tradingFeed: ManagedCandleFeed | undefined;
  let htfFeed: ManagedCandleFeed | undefined;
  let atrSource: AtrSource;

  let bookTickerFeed: ManagedBookFeed | undefined;
  let userDataFeed: BinanceUserDataFeed | undefined;
  let dashboard: DashboardServer | null = null;
  let gridRef: IStrategy | undefined;

  const resolveAlpacaFeedCreds = (overrideCfg?: Record<string, any>) => {
    const rt = gridRef?.getRuntimeConfig?.() ?? config;
    const rawKey = overrideCfg?.alpacaApiKey && overrideCfg.alpacaApiKey !== "******"
      ? overrideCfg.alpacaApiKey
      : (gridRef?.getRealAlpacaApiKey?.() || config.alpacaApiKey || "");
    const rawSecret = overrideCfg?.alpacaApiSecret && overrideCfg.alpacaApiSecret !== "******"
      ? overrideCfg.alpacaApiSecret
      : (gridRef?.getRealAlpacaApiSecret?.() || config.alpacaApiSecret || "");
    return {
      apiKey: String(rawKey || "").trim(),
      apiSecret: String(rawSecret || "").trim(),
      dataUrl: String(overrideCfg?.alpacaDataUrl || rt.alpacaDataUrl || config.alpacaDataUrl || "https://data.alpaca.markets"),
    };
  };

  // Map trading symbol (which may be on DreamDEX like SOMI, SOMI:USDSO, WBTC, WETH)
  // to a liquid Binance Spot Symbol for 100% reliable candlestick data & ATR calculations!
  const resolveBinanceCandleSymbol = (sym: string): string => {
    const s = sym.toUpperCase().replace(/[\/\-_:]/g, "");
    if (s.startsWith("SOMI")) return "SOMIUSDT";
    if (s.startsWith("USDC") || s === "USDSO") return "USDCUSDT";
    if (s.startsWith("WBTC") || s === "BTC") return "BTCUSDT";
    if (s.startsWith("WETH") || s === "ETH") return "ETHUSDT";
    // If symbol does not end with USDT, USDC, FDUSD, etc., default to appending USDT
    if (!s.endsWith("USDT") && !s.endsWith("USDC") && !s.endsWith("FDUSD")) {
      return `${s}USDT`;
    }
    return s;
  };

  const loadEngineCandlesForExchange = async (
    engine: DowStructureEngine,
    sym: string,
    interval: string,
    limit: number,
  ): Promise<void> => {
    if (exchange.exchangeName === "alpaca") {
      const creds = resolveAlpacaFeedCreds();
      try {
        const bars = await fetchAlpacaBars({
          symbol: sym,
          interval,
          limit,
          apiKey: creds.apiKey,
          apiSecret: creds.apiSecret,
          dataUrl: creds.dataUrl,
        });
        engine.setCandles(bars, true);
        log(`🇺🇸 Loaded ${bars.length} Alpaca historical bars (${normalizeStockSymbol(sym)} ${interval})`);
      } catch (err) {
        log(`⚠️ Failed to load Alpaca bars (${normalizeStockSymbol(sym)} ${interval}): ${(err as Error).message}`);
      }
      return;
    }
    await engine.loadHigherTimeframeCandles(
      resolveBinanceCandleSymbol(sym),
      interval,
      config.binanceBaseUrl,
      log,
      limit,
      true,
    );
  };

  const createCandleFeedForExchange = (
    sym: string,
    interval: string,
    initialCandleCount: number,
    tag: string,
  ): ManagedCandleFeed => {
    if (exchange.exchangeName === "alpaca") {
      const creds = resolveAlpacaFeedCreds();
      return new AlpacaAtrFeed(
        {
          symbol: normalizeStockSymbol(sym),
          interval,
          apiKey: creds.apiKey,
          apiSecret: creds.apiSecret,
          dataUrl: creds.dataUrl,
          staleMs: 180_000,
          initialCandleCount,
        },
        config.atrLookback,
        (msg) => log(`[${tag}] ${msg}`),
      );
    }
    return new BinanceAtrFeed(
      {
        symbol: resolveBinanceCandleSymbol(sym).toLowerCase(),
        interval,
        wsBase: config.binanceWsBase,
        staleMs: config.binanceStaleMs,
        initialCandleCount,
      },
      config.atrLookback,
      (msg) => log(`[${tag}] ${msg}`),
    );
  };

  const initFeeds = async (sym: string) => {
    const isAlpaca = exchange.exchangeName === "alpaca";
    const feedSymLabel = isAlpaca ? normalizeStockSymbol(sym) : resolveBinanceCandleSymbol(sym);

    log(`📈 Initializing ${isAlpaca ? "Alpaca US Equities" : "Binance"} market feeds for ${sym} -> using symbol: ${feedSymLabel}`);

    macroDowEngine.clearCandles();
    localTrendEngine.clearCandles();
    htfDowEngine.clearCandles();

    const isMaRibbon = config.strategyType === "ma_ribbon";
    const primaryInterval = isMaRibbon ? ((config.maFanExecutionTimeframe as string) || "5m") : config.dowTimeframe;
    const htfInterval = isMaRibbon ? ((config.maFanSupervisorTimeframe as string) || "15m") : config.htfTimeframe;
    const initialCandleLimit = isMaRibbon ? 1000 : (config.initialCandleCount ?? 300);

    if (isMaRibbon) {
      macroDowEngine.setMaxCandles(1400);
      dashboard?.setMaxCandles?.(1400);
    }

    await Promise.all([
      loadEngineCandlesForExchange(macroDowEngine, sym, primaryInterval, initialCandleLimit),
      loadEngineCandlesForExchange(localTrendEngine, sym, config.tradingTimeframe, config.initialCandleCount ?? 300),
      loadEngineCandlesForExchange(htfDowEngine, sym, htfInterval, 300),
    ]);
    dashboard?.setInitialHtfCandles(htfDowEngine.getCandles());

    macroFeed?.stop();
    tradingFeed?.stop();
    htfFeed?.stop();
    bookTickerFeed?.stop();
    userDataFeed?.stop();
    userDataFeed = undefined;

    macroFeed = createCandleFeedForExchange(sym, primaryInterval, initialCandleLimit, `macro ${primaryInterval}`);
    tradingFeed = createCandleFeedForExchange(sym, config.tradingTimeframe, config.initialCandleCount ?? 300, `trading ${config.tradingTimeframe}`);

    tradingFeed.onCandle((candle, isClosed) => {
      if (isClosed) {
        localTrendEngine.addCandle(candle);
      }
    });

    htfFeed = createCandleFeedForExchange(sym, htfInterval, 150, `htf ${htfInterval}`);

    htfFeed.onCandle((candle, isClosed) => {
      if (isClosed) {
        htfDowEngine.addCandle(candle);
        dashboard?.addHtfCandle(candle, isClosed);
        (grid as any).onHtfCandleClosed?.(candle);
      }
    });

    // Real-time Top-of-Book feed (Binance WS or Alpaca Data API snapshot polling)
    if (isAlpaca) {
      const creds = resolveAlpacaFeedCreds();
      bookTickerFeed = new AlpacaBookTickerFeed(
        {
          symbol: normalizeStockSymbol(sym),
          apiKey: creds.apiKey,
          apiSecret: creds.apiSecret,
          dataUrl: creds.dataUrl,
        },
        (msg) => log(`[alpaca bookTicker] ${msg}`),
      );
    } else {
      bookTickerFeed = new BinanceBookTickerFeed(
        feedSymLabel.toLowerCase(),
        config.binanceWsBase,
        (msg) => log(`[bookTicker] ${msg}`),
      );
    }

    // Real-Time User Data Stream WebSocket feed (if on Binance with API credentials)
    if (exchange.exchangeName === "binance" && exchange.hasCredentials()) {
      userDataFeed = new BinanceUserDataFeed(
        {
          getCredentials: () => (exchange as any).getCredentials?.() ?? {
            apiKey: config.binanceApiKey,
            apiSecret: config.binanceApiSecret,
          },
          getTimeOffset: () => (exchange as any).getTimeOffset?.() ?? 0,
        },
        "wss://ws-api.binance.com:443/ws-api/v3",
        (msg) => log(`[userData] ${msg}`),
      );
    }

    atrSource = tradingFeed;
  };

  await initFeeds(symbolInfo.symbol);

  // Fetch initial balances
  let initialBaseBal = 0;
  let initialQuoteBal = 0;
  if (exchange.hasCredentials()) {
    try {
      const b = await exchange.getAccountBalances(symbolInfo.symbol);
      initialBaseBal = b.baseFree;
      initialQuoteBal = b.quoteFree;
    } catch (err) {
      log(`warning: failed to query initial ${exchange.exchangeName} balance: ${(err as Error).message}`);
    }
  } else {
    log(`ℹ️ Running without ${exchange.exchangeName} API credentials (public market data / dryRun mode).`);
  }

  log(
    `${exchange.exchangeName.toUpperCase()} Spot balance=[${initialBaseBal} ${symbolInfo.baseAsset} | ${initialQuoteBal.toFixed(2)} ${symbolInfo.quoteAsset}] ` +
      `symbol=${symbolInfo.symbol} maxInv=$${config.maxInventoryQuote} dryRun=${config.dryRun} ` +
      `trendFilter=${config.dowTrendFilter} (${config.trendTimeframe})`,
  );

  let grid: IStrategy = createStrategy(config.strategyType, {
    exchange,
    symbolInfo,
    config,
    atrSource: atrSource!,
    log,
    macroDowEngine,
    localTrendEngine,
    htfDowEngine,
  });
  gridRef = grid;
  await grid.syncOnChainOrders();
  if (exchange.exchangeName === "binance" && !config.dryRun && exchange.hasCredentials()) {
    try {
      await grid.getDatabase().syncRecentTradesFromBinance(exchange, activeSymbol);
      grid.reloadState();
    } catch (err: any) {
      log(`⚠️ Failed to sync trades from Binance on boot: ${err.message}`);
    }
  }
  await grid.refreshWalletBalances();

  // 🛡️ Safe Boot: Always ensure bot starts in PAUSED mode on startup across all strategies
  grid.setPaused(true);
  log("⏸️ [SAFE BOOT] Bot started in PAUSED mode as requested. Resume trading via dashboard or API.");

  let wakeSleep: (() => void) | null = null;
  const interruptibleSleep = (ms: number): Promise<void> => {
    return new Promise((resolve) => {
      let timer: NodeJS.Timeout | null = setTimeout(() => {
        wakeSleep = null;
        resolve();
      }, ms);
      wakeSleep = () => {
        if (timer) {
          clearTimeout(timer);
          timer = null;
        }
        wakeSleep = null;
        resolve();
      };
    });
  };

  const wireFeedsToGrid = () => {
    if (bookTickerFeed) {
      bookTickerFeed.onBook((b) => grid.handleWsBookTicker?.(b));
      bookTickerFeed.start();
    }
    if (userDataFeed) {
      userDataFeed.onExecutionReport((rep) => grid.handleWsExecutionReport?.(rep));
      userDataFeed.onAccountUpdate((acc) => grid.handleWsAccountUpdate?.(acc));
      userDataFeed.start().catch((err) => log(`⚠️ User data stream start error: ${(err as Error).message}`));
    }
  };

  // ── Real-Time Dashboard Server & Dynamic Config API ───────────────────────
  let onUpdateSettings: (s: Record<string, any>) => Promise<Record<string, any>>;

  onUpdateSettings = async (s) => {
      const prevConfig = grid.getRuntimeConfig();
      const prevInitial = prevConfig.initialCandleCount;
      const prevMax = prevConfig.maxCandleCount;
      const prevTf = prevConfig.dowTimeframe;
      const prevTradingTf = prevConfig.tradingTimeframe;
      const prevHtfTf = prevConfig.htfTimeframe;
      const prevSymbol = prevConfig.symbol;
      const prevMaFanExecTf = prevConfig.maFanExecutionTimeframe;
      const prevMaFanSupTf = prevConfig.maFanSupervisorTimeframe;

      const targetExchangeName = (s.exchange || prevConfig.exchange || "binance").toLowerCase();
      const exchangeChanged = Boolean(s.exchange && targetExchangeName !== (prevConfig.exchange || "binance").toLowerCase());
      const privateKeyChanged = s.dreamdexPrivateKey && s.dreamdexPrivateKey !== "******";
      const alpacaCredsChanged = Boolean(
        (s.alpacaApiKey && s.alpacaApiKey !== "******") ||
        (s.alpacaApiSecret && s.alpacaApiSecret !== "******") ||
        (s.alpacaBaseUrl && s.alpacaBaseUrl !== prevConfig.alpacaBaseUrl) ||
        (s.alpacaDataUrl && s.alpacaDataUrl !== prevConfig.alpacaDataUrl),
      );

      const normPrevSymbol = (prevSymbol || "").toUpperCase().replace(/[\/\-_:]/g, "");
      let normNextSymbol = (s.symbol || "").toUpperCase().replace(/[\/\-_:]/g, "");

      // 🛡️ DreamDEX Accidental CEX Symbol Guard:
      // If running on DreamDEX and incoming symbol is an accidental CEX symbol (e.g. BTCUSDT, BTCFDUSD, ETHUSDT)
      // while user was trading SOMI/USDSO, ignore the accidental switch and preserve active SOMI pair!
      if (!exchangeChanged && targetExchangeName === "dreamdex" && (normNextSymbol === "BTCUSDT" || normNextSymbol === "BTCFDUSD" || normNextSymbol === "ETHUSDT" || normNextSymbol === "ETHFDUSD")) {
        if (normPrevSymbol.startsWith("SOMI") || !normPrevSymbol) {
          log(`🛡️ [SYMBOL GUARD] Ignored accidental CEX symbol '${normNextSymbol}' on DreamDEX; keeping active pair '${prevSymbol || "SOMI:USDSO"}'`);
          normNextSymbol = normPrevSymbol || "SOMIUSDSO";
          s.symbol = prevSymbol || "SOMI:USDSO";
        }
      }

      // 🛡️ Alpaca Accidental Crypto Symbol Guard:
      if (!exchangeChanged && targetExchangeName === "alpaca" && ["BTCUSDT", "BTCFDUSD", "ETHUSDT", "ETHFDUSD", "SOMIUSDSO", "SOMI"].includes(normNextSymbol)) {
        const keepStock = normalizeStockSymbol(prevSymbol || "AAPL") || "AAPL";
        log(`🛡️ [SYMBOL GUARD] Ignored accidental crypto symbol '${normNextSymbol}' on Alpaca; keeping active ticker '${keepStock}'`);
        normNextSymbol = keepStock;
        s.symbol = keepStock;
      }
      if (targetExchangeName === "alpaca" && normNextSymbol) {
        normNextSymbol = normalizeStockSymbol(normNextSymbol);
      }

      const symbolChanged = Boolean(normNextSymbol && normNextSymbol !== normPrevSymbol);

      // Lock Trading Pair & Exchange switch when bot holds a REAL active position (ignore residual dust < $1.00)
      const refPrice = grid.lastRefPrice || grid.getAvgEntryPrice?.() || 1;
      const heldAmount = grid.baseHeld();
      const notionalHeld = heldAmount * refPrice;
      const minQty = symbolInfo?.minQty ?? 0.0001;
      const isDust = notionalHeld < 1.0 || (heldAmount < minQty * 2 && notionalHeld < 2.0);
      const isHoldingPosition = !isDust && heldAmount >= minQty && grid.getLots().length > 0;

      if (symbolChanged || exchangeChanged) {
        if (isHoldingPosition) {
          const lotCount = grid.getLots().length;
          const baseName = symbolInfo?.baseAsset || "tokens";
          const errMsg = `Cannot switch trading pair or exchange while holding active position (${heldAmount.toFixed(4)} ${baseName} | ${notionalHeld.toFixed(2)} held across ${lotCount} lot(s)). Please exit or close position first.`;
          log(`⛔ [PAIR SWITCH BLOCKED] ${errMsg}`);
          throw new Error(errMsg);
        } else if (isDust && (heldAmount > 0 || grid.getLots().length > 0)) {
          log(`🧹 [PAIR SWITCH] Auto-cleared residual dust position (${heldAmount.toFixed(4)} ${symbolInfo?.baseAsset || "tokens"} | ${notionalHeld.toFixed(4)}) before switching trading pair.`);
          grid.clearPositionState?.();
          grid.saveState(true);
        }
      }

      const res = grid.updateRuntimeSettings(s);

      // 1. Handle Exchange Adapter switch or credentials update dynamically
      if (
        exchangeChanged ||
        (targetExchangeName === "dreamdex" && privateKeyChanged) ||
        (targetExchangeName === "alpaca" && alpacaCredsChanged)
      ) {
        grid.setSwitchingSymbol(true);
        try {
          // If switching exchange or symbol, cancel all resting orders on the current exchange/pair first
          if (exchangeChanged || symbolChanged) {
            await grid.prepareForSymbolSwitch(normNextSymbol || targetExchangeName.toUpperCase());
          }

          const realPrivateKey = (s.dreamdexPrivateKey !== undefined && s.dreamdexPrivateKey !== "******" && s.dreamdexPrivateKey.trim() !== "")
            ? s.dreamdexPrivateKey.trim()
            : grid.getRealDreamdexPrivateKey();

          const realApiSecret = (s.binanceApiSecret !== undefined && s.binanceApiSecret !== "******")
            ? s.binanceApiSecret
            : grid.getRealBinanceApiSecret();

          const realApiKey = (s.binanceApiKey !== undefined && s.binanceApiKey !== "******")
            ? s.binanceApiKey
            : grid.getRealBinanceApiKey();

          const realAlpacaKey = (s.alpacaApiKey !== undefined && s.alpacaApiKey !== "******" && String(s.alpacaApiKey).trim() !== "")
            ? String(s.alpacaApiKey).trim()
            : (grid.getRealAlpacaApiKey?.() || config.alpacaApiKey);

          const realAlpacaSecret = (s.alpacaApiSecret !== undefined && s.alpacaApiSecret !== "******" && String(s.alpacaApiSecret).trim() !== "")
            ? String(s.alpacaApiSecret).trim()
            : (grid.getRealAlpacaApiSecret?.() || config.alpacaApiSecret);

          exchange.destroy?.();
          const newExchange = buildExchangeAdapter(targetExchangeName, {
            binanceApiKey: realApiKey,
            binanceApiSecret: realApiSecret,
            binanceBaseUrl: s.binanceBaseUrl || prevConfig.binanceBaseUrl,
            dreamdexPrivateKey: (realPrivateKey && realPrivateKey !== "******") ? realPrivateKey : undefined,
            dreamdexRpcUrl: s.dreamdexRpcUrl || prevConfig.dreamdexRpcUrl,
            alpacaApiKey: realAlpacaKey,
            alpacaApiSecret: realAlpacaSecret,
            alpacaBaseUrl: s.alpacaBaseUrl || prevConfig.alpacaBaseUrl || config.alpacaBaseUrl,
            alpacaDataUrl: s.alpacaDataUrl || prevConfig.alpacaDataUrl || config.alpacaDataUrl,
          });
          await newExchange.syncTime();
          exchange = newExchange;

          // Map default symbol appropriately when switching exchanges
          let targetSymbol = (s.symbol || prevConfig.symbol || (targetExchangeName === "alpaca" ? "AAPL" : "BTCUSDT")).toUpperCase().replace(/[\/\-_:]/g, "");
          if (targetExchangeName === "dreamdex" && (targetSymbol.includes("FDUSD") || targetSymbol.includes("USDT") || targetSymbol === "BTCUSDT")) {
            targetSymbol = "SOMI";
          } else if (targetExchangeName === "alpaca") {
            const cleanedStock = normalizeStockSymbol(targetSymbol);
            if (!cleanedStock || cleanedStock.endsWith("USDT") || cleanedStock.endsWith("FDUSD") || cleanedStock.endsWith("USDSO") || cleanedStock === "SOMI") {
              targetSymbol = "AAPL";
            } else {
              targetSymbol = cleanedStock;
            }
          }

          const nextInfo = await exchange.getExchangeInfo(targetSymbol);
          if ((exchange.exchangeName === "binance" || exchange.exchangeName === "alpaca") && nextInfo.status && nextInfo.status !== "TRADING") {
            throw new Error(`Symbol ${nextInfo.symbol} is currently suspended/halted by ${exchange.exchangeName} (Status: ${nextInfo.status}). Cannot trade.`);
          }
          symbolInfo = nextInfo;
          await initFeeds(nextInfo.symbol);
          grid.updateExchangeClient(newExchange, nextInfo, atrSource!);
          wireFeedsToGrid();
          await grid.refreshWalletBalances();
          await grid.syncOnChainOrders();
          await grid.refreshWalletBalances();
          dashboard.resetState({ clearTrades: true });
          dashboard.setInitialOrders(grid.getRecentOrders());
          dashboard.setInitialCandles(macroDowEngine.getCandles());
          macroFeed?.onCandle((candle, isClosed) => {
            macroDowEngine.addCandle(candle);
            dashboard.addCandle(candle, isClosed);
            if (isClosed) {
              grid.onCandleClosed(candle);
              wakeSleep?.();
            }
          });
          macroFeed?.start();
          tradingFeed?.start();
          htfFeed?.start();
          wakeSleep?.();
          log(`🔄 Successfully switched Exchange Adapter to: ${exchange.exchangeName.toUpperCase()} (${nextInfo.symbol})`);
        } catch (err) {
          log(`⚠️ Failed to switch exchange adapter to ${targetExchangeName}: ${(err as Error).message}`);
        } finally {
          grid.setSwitchingSymbol(false);
        }
      } else if (symbolChanged) {
        // 2. Handle trading pair change dynamically on same exchange
        const nextSymbolStr = normNextSymbol;
        grid.setSwitchingSymbol(true);
        try {
          // Validate symbol on exchange first before cancelling existing orders
          const nextInfo = await exchange.getExchangeInfo(nextSymbolStr);
          if ((exchange.exchangeName === "binance" || exchange.exchangeName === "alpaca") && nextInfo.status && nextInfo.status !== "TRADING") {
            throw new Error(`Symbol ${nextInfo.symbol} is currently suspended/halted by ${exchange.exchangeName} (Status: ${nextInfo.status}). Cannot trade.`);
          }
          // Cancel all resting orders on the old pair (and sweep any orphan quote-locking orders) before switching
          await grid.prepareForSymbolSwitch(nextInfo.symbol);
          symbolInfo = nextInfo;
          await initFeeds(nextInfo.symbol);
          grid.updateSymbolInfo(nextInfo, atrSource!);
          grid.getDatabase().setSetting("symbol", nextInfo.symbol);
          if (exchange.exchangeName === "binance") {
            grid.getDatabase().setSetting("binanceSymbol", nextInfo.symbol.toLowerCase());
          }
          wireFeedsToGrid();
          // Immediately refresh unlocked wallet balances & open orders before the first tick on the new pair
          await grid.refreshWalletBalances();
          await grid.syncOnChainOrders();
          await grid.refreshWalletBalances();
          dashboard.resetState({ clearTrades: true });
          dashboard.setInitialOrders(grid.getRecentOrders());
          dashboard.setInitialCandles(macroDowEngine.getCandles());
          macroFeed?.onCandle((candle, isClosed) => {
            macroDowEngine.addCandle(candle);
            dashboard.addCandle(candle, isClosed);
            if (isClosed) {
              grid.onCandleClosed(candle);
              wakeSleep?.();
            }
          });
          macroFeed?.start();
          tradingFeed?.start();
          htfFeed?.start();
          wakeSleep?.();
          log(`🔄 Switched active ${exchange.exchangeName} trading pair to: ${nextInfo.symbol}`);
        } catch (err) {
          // Restore previous symbol in settings if getExchangeInfo failed
          if (prevSymbol) {
            grid.updateRuntimeSettings({ symbol: prevSymbol });
          }
          log(`⚠️ Failed to switch symbol to ${nextSymbolStr}: ${(err as Error).message}`);
          throw err;
        } finally {
          grid.setSwitchingSymbol(false);
        }
      }

      // 3. Handle Strategy Type switch dynamically (e.g. Dynamic Grid <-> Swing Trade <-> MA-Ribbon)
      const rawNextStrat = s.strategyType || s.strategyMode;
      const nextStrat = rawNextStrat ? normalizeStrategyType(rawNextStrat) : undefined;
      if (nextStrat && nextStrat !== prevConfig.strategyType) {
        log(`🔄 [STRATEGY SWITCH] Switching active strategy from ${prevConfig.strategyType || "dynamic_grid"} to ${nextStrat}...`);
        try {
          await grid.cancelAllOrdersUser();
          const targetStrategyType = nextStrat;
          const currentConfig = grid.getRuntimeConfig();
          const cleanS = { ...s };
          if (cleanS.binanceApiKey === "******") delete cleanS.binanceApiKey;
          if (cleanS.binanceApiSecret === "******") delete cleanS.binanceApiSecret;
          if (cleanS.dreamdexPrivateKey === "******") delete cleanS.dreamdexPrivateKey;
          if (cleanS.alpacaApiKey === "******") delete cleanS.alpacaApiKey;
          if (cleanS.alpacaApiSecret === "******") delete cleanS.alpacaApiSecret;
          const mergedConfig = {
            ...currentConfig,
            ...cleanS,
            strategyType: targetStrategyType,
            binanceApiKey: grid.getRealBinanceApiKey() || config.binanceApiKey,
            binanceApiSecret: grid.getRealBinanceApiSecret() || config.binanceApiSecret,
            dreamdexPrivateKey: grid.getRealDreamdexPrivateKey() || config.dreamdexPrivateKey,
            alpacaApiKey: grid.getRealAlpacaApiKey?.() || config.alpacaApiKey,
            alpacaApiSecret: grid.getRealAlpacaApiSecret?.() || config.alpacaApiSecret,
          };
          config.strategyType = targetStrategyType;
          await initFeeds(symbolInfo.symbol);
          dashboard.setInitialCandles(macroDowEngine.getCandles());
          dashboard.setInitialHtfCandles(htfDowEngine.getCandles());

          grid = createStrategy(targetStrategyType, {
            exchange,
            symbolInfo,
            config: mergedConfig,
            atrSource: atrSource!,
            log,
            macroDowEngine,
            localTrendEngine,
            htfDowEngine,
          });
          gridRef = grid;
          grid.updateRuntimeSettings(s);
          grid.getDatabase().setSetting("strategyType", targetStrategyType);
          wireFeedsToGrid();
          macroFeed?.onCandle((candle, isClosed) => {
            macroDowEngine.addCandle(candle);
            dashboard.addCandle(candle, isClosed);
            if (isClosed) {
              grid.onCandleClosed(candle);
              wakeSleep?.();
            }
          });
          macroFeed?.start();
          tradingFeed?.start();
          htfFeed?.start();
          grid.onEvent((event) => {
            if (event.type === "tick") {
              dashboard.updateTick(event.data);
            } else if (event.type === "order") {
              dashboard.addOrder(event.data);
            } else if (event.type === "order_gas") {
              dashboard.updateOrderGas(event.data.txHash, event.data.gasFeeBase, event.data.gasFeeQuote);
            }
          });
          await grid.syncOnChainOrders();
          await grid.refreshWalletBalances();
          dashboard.setInitialOrders(grid.getRecentOrders());
          grid.emitTelemetryTick();
          wakeSleep?.();
          log(`✅ [STRATEGY SWITCH] Active strategy is now: ${grid.name} (${grid.strategyType})`);
        } catch (stratErr) {
          log(`⚠️ Failed to switch strategy dynamically: ${(stratErr as Error).message}`);
        }
      }

      if (s.maxCandleCount && s.maxCandleCount !== prevMax) {
        dashboard.setMaxCandles(s.maxCandleCount);
        macroDowEngine.setMaxCandles(s.maxCandleCount);
        localTrendEngine.setMaxCandles(s.maxCandleCount);
        htfDowEngine.setMaxCandles(s.maxCandleCount);
      }

      // If initialCandleCount changed or timeframe changed, re-fetch candles & restart WebSocket kline feeds
      if (
        (s.initialCandleCount && s.initialCandleCount !== prevInitial) ||
        (s.dowTimeframe && s.dowTimeframe !== prevTf) ||
        (s.tradingTimeframe && s.tradingTimeframe !== prevTradingTf) ||
        (s.htfTimeframe && s.htfTimeframe !== prevHtfTf) ||
        (s.maFanExecutionTimeframe && s.maFanExecutionTimeframe !== prevMaFanExecTf) ||
        (s.maFanSupervisorTimeframe && s.maFanSupervisorTimeframe !== prevMaFanSupTf)
      ) {
        if (config.strategyType === "ma_ribbon") {
          if (s.maFanExecutionTimeframe) config.maFanExecutionTimeframe = s.maFanExecutionTimeframe;
          if (s.maFanSupervisorTimeframe) config.maFanSupervisorTimeframe = s.maFanSupervisorTimeframe;
          await initFeeds(symbolInfo.symbol);
          if ((grid as any).updateSymbolInfo) {
            (grid as any).updateSymbolInfo(symbolInfo, atrSource!);
          }
          wireFeedsToGrid();
          dashboard.setInitialCandles(macroDowEngine.getCandles());
          dashboard.setInitialHtfCandles(htfDowEngine.getCandles());
          macroFeed?.onCandle((candle, isClosed) => {
            macroDowEngine.addCandle(candle);
            dashboard.addCandle(candle, isClosed);
            if (isClosed) {
              grid.onCandleClosed(candle);
              wakeSleep?.();
            }
          });
          macroFeed?.start();
          tradingFeed?.start();
          htfFeed?.start();
          wakeSleep?.();
          return res;
        }
        const isMaRibbonStrategy = normalizeStrategyType(s.strategyType || s.strategyMode || config.strategyType) === "ma_ribbon";
        const fetchLimit = isMaRibbonStrategy ? 1000 : (s.initialCandleCount ?? res.initialCandleCount ?? 300);
        const tf = s.dowTimeframe ?? res.dowTimeframe ?? config.dowTimeframe;
        const microTf = s.tradingTimeframe ?? res.tradingTimeframe ?? config.tradingTimeframe ?? "5m";
        try {
          if ((s.dowTimeframe && s.dowTimeframe !== prevTf) || (s.initialCandleCount && s.initialCandleCount !== prevInitial)) {
            await loadEngineCandlesForExchange(macroDowEngine, symbolInfo.symbol, tf, fetchLimit);
            dashboard.setInitialCandles(macroDowEngine.getCandles());
            log(`🔄 Reloaded ${fetchLimit} candles (${tf}) following settings update`);

            macroFeed?.stop();
            macroFeed = createCandleFeedForExchange(symbolInfo.symbol, tf, fetchLimit, `macro ${tf}`);
            macroFeed.onCandle((candle, isClosed) => {
              macroDowEngine.addCandle(candle);
              dashboard.addCandle(candle, isClosed);
              if (isClosed) {
                grid.onCandleClosed(candle);
                wakeSleep?.();
              }
            });
            macroFeed.start();
            (grid as any).resetConfirmedChannel?.();
            wakeSleep?.();
          }

          if ((s.tradingTimeframe && s.tradingTimeframe !== prevTradingTf) || (s.initialCandleCount && s.initialCandleCount !== prevInitial)) {
            await loadEngineCandlesForExchange(localTrendEngine, symbolInfo.symbol, microTf, fetchLimit);
            log(`🔄 Reloaded ${fetchLimit} micro candles (${microTf}) following settings update`);

            tradingFeed?.stop();
            tradingFeed = createCandleFeedForExchange(symbolInfo.symbol, microTf, fetchLimit, `trading ${microTf}`);
            tradingFeed.onCandle((candle, isClosed) => {
              if (isClosed) {
                localTrendEngine.addCandle(candle);
              }
            });
            tradingFeed.start();
            grid.atrSource = tradingFeed;
            log(`🔄 Re-subscribed market stream to micro timeframe: ${microTf}`);
          }

          if (s.htfTimeframe && s.htfTimeframe !== prevHtfTf) {
            const htfTf = s.htfTimeframe ?? config.htfTimeframe;
            await loadEngineCandlesForExchange(htfDowEngine, symbolInfo.symbol, htfTf, 300);
            dashboard?.setInitialHtfCandles(htfDowEngine.getCandles());
            log(`🔄 Reloaded HTF candles (${htfTf}) following settings update`);

            htfFeed?.stop();
            htfFeed = createCandleFeedForExchange(symbolInfo.symbol, htfTf, 300, `htf ${htfTf}`);
            htfFeed.onCandle((candle, isClosed) => {
              if (isClosed) {
                htfDowEngine.addCandle(candle);
                dashboard?.addHtfCandle(candle, isClosed);
                (grid as any).onHtfCandleClosed?.(candle);
              }
            });
            htfFeed.start();
            log(`🔄 Re-subscribed market stream to HTF timeframe: ${htfTf}`);
          }
        } catch (err) {
          log(`⚠️ Failed to reload candles on settings update: ${(err as Error).message}`);
        }
      }

      grid.emitTelemetryTick();
      wakeSleep?.();
      return grid.getRuntimeConfig();
  };

  dashboard = new DashboardServer({
    port: config.dashboardPort,
    log,
    db: grid.getDatabase(),
    maxCandles: config.strategyType === "ma_ribbon" ? 1200 : (config.maxCandleCount ?? 600),
    getSettings: () => grid.getRuntimeConfig(),
    onUpdateSettings: (s) => onUpdateSettings(s),
    onPauseBot: (paused) => grid.setPaused(paused),
    getIsPaused: () => grid.getIsPaused(),
    onCancelAll: () => grid.cancelAllOrdersUser(),
    onSellAll: () => grid.sellAllUser(),
    onResetBot: (opts) => grid.resetBotState(opts),
    onResetPosition: async () => {
      const res = await grid.resetPosition();
      const currentSym = grid.getRuntimeConfig().symbol || activeSymbol;
      grid.getDatabase().clearLots(currentSym);
      if (grid.getSymbolKey) grid.getDatabase().clearLots(grid.getSymbolKey());
      return res;
    },
    onReloadState: () => {
      grid.reloadState();
      grid.emitTelemetryTick();
    },
    getRotationStatus: () => pairRotator.getStatus(grid.getRuntimeConfig().symbol || activeSymbol, grid.getRuntimeConfig()),
    onTriggerRotationScan: async (opts) => {
      const cfg = grid.getRuntimeConfig();
      const currentSym = cfg.symbol || activeSymbol;
      if (opts?.forceRotate) {
        const refP = grid.lastRefPrice || grid.getAvgEntryPrice?.() || 1;
        const heldVal = grid.baseHeld() * refP;
        const isHolding = heldVal >= 1.0 || grid.getLots().length > 0;
        if (isHolding) {
          return {
            rotated: false,
            report: pairRotator.getStatus(currentSym, cfg).latestCandidates,
            reason: `Cannot force rotate while holding position (${grid.baseHeld().toFixed(4)} ${(grid as any).baseAsset || currentSym} ≈ ${heldVal.toFixed(2)}). Exit position first!`,
          };
        }
      }
      const res = await pairRotator.evaluateAndRotate({
        currentSymbol: currentSym,
        trigger: "MANUAL_FORCE",
        cfg,
        forceRotate: opts?.forceRotate,
        quoteAsset: opts?.quoteAsset,
      });
      if (res.rotated && res.targetSymbol) {
        log(`🚀 [MANUAL ROTATION] Rotating from ${currentSym} to ${res.targetSymbol} (${res.reason})`);
        await onUpdateSettings({ symbol: res.targetSymbol });
      }
      return res;
    },
    onSyncExchangeTrades: async () => {
      const cfg = grid.getRuntimeConfig();
      const currentSym = cfg.symbol || activeSymbol;
      let res: { success: boolean; synced: number; purged?: number; error?: string };
      if (exchange.exchangeName === "binance") {
        res = await grid.getDatabase().syncRecentTradesFromBinance(exchange, currentSym);
      } else {
        res = { success: false, synced: 0, error: `Trade reconciliation not supported for exchange: ${exchange.exchangeName}` };
      }
      grid.reloadState();
      await grid.refreshWalletBalances();
      await grid.reconcileInventory?.(true);
      grid.saveState(true);
      grid.emitTelemetryTick();
      return res;
    },
  });

  dashboard.setInitialCandles(macroDowEngine.getCandles());
  dashboard.setInitialHtfCandles(htfDowEngine.getCandles());
  dashboard.setInitialOrders(grid.getRecentOrders());
  dashboard.start();

  wireFeedsToGrid();

  if (macroFeed) {
    macroFeed.onCandle((candle, isClosed) => {
      macroDowEngine.addCandle(candle);
      dashboard.addCandle(candle, isClosed);
      if (isClosed) {
        grid.onCandleClosed(candle);
        wakeSleep?.();
      }
    });
    macroFeed.start();
  }
  tradingFeed?.start();
  htfFeed?.start();

  // Forward strategy events (ticks, buy/sell/cut executions, gas updates) to dashboard
  grid.onEvent((event) => {
    if (event.type === "tick") {
      dashboard.updateTick(event.data);
    } else if (event.type === "order") {
      dashboard.addOrder(event.data);
    } else if (event.type === "order_gas") {
      dashboard.updateOrderGas(event.data.txHash, event.data.gasFeeBase, event.data.gasFeeQuote);
    } else if (event.type === "position_flat") {
      const cfg = grid.getRuntimeConfig();
      if (cfg.enableAutoRotation && !grid.getIsPaused() && exchange.exchangeName === "binance") {
        const currentSym = cfg.symbol || activeSymbol;
        log(`🔄 [AUTO-ROTATION] Detected position flat (cycle closed) -> Evaluating market regime...`);
        setTimeout(async () => {
          try {
            const res = await pairRotator.evaluateAndRotate({
              currentSymbol: currentSym,
              trigger: "POST_ROUND_EXIT",
              cfg,
            });
            if (res.rotated && res.targetSymbol) {
              log(`🚀 [AUTO-ROTATION] Rotating from ${currentSym} to ${res.targetSymbol} (${res.reason})`);
              await onUpdateSettings({ symbol: res.targetSymbol });
            }
          } catch (e: any) {
            log(`⚠️ [AUTO-ROTATION] Evaluation error: ${e.message}`);
          }
        }, 3000);
      }
    }
  });

  let stop = false;
  process.on("SIGINT", () => {
    stop = true;
    wakeSleep?.();
    grid.saveState();
    log("stopping after current tick…");
  });
  process.on("SIGTERM", () => {
    stop = true;
    wakeSleep?.();
    grid.saveState();
  });

  let lastIdleCheckTime = Date.now();
  let alpacaMarketClosedLogged = false;

  while (!stop) {
    let tickSleepOverrideMs = 0;
    try {
      const loopCfg = grid.getRuntimeConfig();
      if (exchange.exchangeName === "alpaca" && !loopCfg.dryRun && !loopCfg.alpacaIgnoreMarketHours && exchange.hasCredentials()) {
        const clock = await exchange.getMarketClock?.();
        if (clock && !clock.isOpen) {
          if (!alpacaMarketClosedLogged) {
            log(`⏸️ [ALPACA MARKET CLOSED] US Equities market is closed (next open: ${clock.nextOpen}). Holding live order execution until market opens.`);
            alpacaMarketClosedLogged = true;
          }
          grid.emitTelemetryTick();
          tickSleepOverrideMs = 15_000;
        } else if (clock?.isOpen && alpacaMarketClosedLogged) {
          log(`🔔 [ALPACA MARKET OPEN] US Equities market is now OPEN — resuming live ticks.`);
          alpacaMarketClosedLogged = false;
        }
      } else {
        alpacaMarketClosedLogged = false;
      }

      if (tickSleepOverrideMs === 0) {
        await grid.tick();
      }
      // Periodic Idle Cash Check (every 60s) for Auto-Rotation
      if (Date.now() - lastIdleCheckTime >= 60_000) {
        lastIdleCheckTime = Date.now();
        const cfg = grid.getRuntimeConfig();
        if (cfg.enableAutoRotation && !grid.getIsPaused() && exchange.exchangeName === "binance") {
          const refP = grid.lastRefPrice || grid.getAvgEntryPrice?.() || 1;
          const heldVal = grid.baseHeld() * refP;
          if (heldVal < 1.0 && grid.getLots().length > 0) {
            log(`🧹 [AUTO-ROTATION] Auto-cleared residual dust lots (${grid.baseHeld().toFixed(4)} tokens | ${heldVal.toFixed(3)}) before idle cash evaluation.`);
            grid.clearPositionState?.();
            grid.saveState(true);
          }
          const isFlat = grid.baseHeld() * refP < 1.0 && grid.getLots().length === 0;
          if (isFlat) {
            const flatDurationMs = Date.now() - (grid.lastFlatCashTime || Date.now());
            const maxIdleMs = (cfg.rotationIdleCashMinutes || 120) * 60_000;
            if (flatDurationMs >= maxIdleMs) {
              const currentSym = cfg.symbol || activeSymbol;
              grid.lastFlatCashTime = Date.now();
              log(`⏳ [AUTO-ROTATION] Idle cash timeout (${(flatDurationMs / 60_000).toFixed(0)}m / ${cfg.rotationIdleCashMinutes}m) -> Evaluating market regime...`);
              try {
                const res = await pairRotator.evaluateAndRotate({
                  currentSymbol: currentSym,
                  trigger: "IDLE_CASH_TIMEOUT",
                  cfg,
                });
                if (res.rotated && res.targetSymbol) {
                  log(`🚀 [AUTO-ROTATION] Rotating from ${currentSym} to ${res.targetSymbol} (${res.reason})`);
                  await onUpdateSettings({ symbol: res.targetSymbol });
                }
              } catch (e: any) {
                log(`⚠️ [AUTO-ROTATION] Evaluation error: ${e.message}`);
              }
            }
          }
        }
      }
    } catch (err) {
      log("tick error", (err as Error).message);
    }
    const loopInterval = tickSleepOverrideMs > 0 ? tickSleepOverrideMs : grid.getIntervalMs();
    await interruptibleSleep(loopInterval > 0 ? loopInterval : 1000);
  }

  dashboard.stop();
  macroFeed?.stop();
  tradingFeed?.stop();
  htfFeed?.stop();
  bookTickerFeed?.stop();
  userDataFeed?.stop();
  exchange.destroy?.();
  process.exit(0);
}

main().catch((err) => {
  console.error(`[${getStrategyLogTag()}] fatal:`, err);
  process.exit(1);
});
